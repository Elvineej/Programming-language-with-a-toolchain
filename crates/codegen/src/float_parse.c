static bool digit(char c) { return c >= '0' && c <= '9'; }

static bool word(const char *s, size_t n, const char *lower)
{
    size_t i = 0;
    while (i < n && lower[i]) {
        if (s[i] != lower[i] && s[i] != lower[i] - 'a' + 'A') return false;
        ++i;
    }
    return i == n && !lower[i];
}

static uint64_t high_product(uint64_t a, uint64_t b)
{
    uint64_t al = (uint32_t)a, bl = (uint32_t)b;
    uint64_t ah = a >> 32, bh = b >> 32;
    uint64_t cross = ah * bl + ((al * bl) >> 32);
    uint64_t middle = al * bh + (uint32_t)cross;
    return ah * bh + (cross >> 32) + (middle >> 32);
}

/* Round h * 2^scale, where h has at least 63 bits. */
static uint64_t round_high(uint64_t h, int scale)
{
    int top = (h >> 63) ? 63 : 62;
    int shift = top - 52;
    if (scale + shift < -1074) shift = -1074 - scale;
    if (shift > 63) return shift == 64 && h > SIGN_BIT;
    uint64_t half = UINT64_C(1) << (shift - 1);
    uint64_t rest = h & (half + half - 1);
    uint64_t sig = h >> shift;
    sig += rest > half || (rest == half && (sig & 1));
    int biased = scale + shift + 1075;
    if (biased >= 2047) return INF_BITS;
    return ((uint64_t)(biased - 1) << 52) + sig;
}

/* With normalized w, the exact scaled product lies in [hi,hi+2].
 * One unit bounds the dropped product limb, one the cached-power error. */
static uint64_t product_bound(uint64_t w, int q, bool upper)
{
    int scale = parse_powers[q + 342].e + 1;
    while (!(w & SIGN_BIT)) { w <<= 1; --scale; }
    uint64_t hi = high_product(w, parse_powers[q + 342].m);
    if (upper) {
        if (hi >= UINT64_MAX - 1) return round_high(SIGN_BIT, scale + 1);
        hi += 2;
    }
    return round_high(hi, scale);
}

/* A midpoint has form m*2^k with m < 2^54 and k >= -1075.
 * For negative k its decimal coefficient m*5^-k has at most 768
 * digits. Positive k needs at most 309. Base 10000 fits 800 digits
 * in one fixed buffer. The input is compared directly in its slice. */
struct decimal { uint32_t limb[200]; int used; };

static void mul_add(struct decimal *d, uint32_t factor, uint32_t carry)
{
    for (int i = 0; i < d->used; ++i) {
        uint32_t v = d->limb[i] * factor + carry;
        d->limb[i] = v % 10000;
        carry = v / 10000;
    }
    while (carry) {
        d->limb[d->used++] = carry % 10000;
        carry /= 10000;
    }
}

/* Compare the input magnitude to the midpoint above binary encoding b,
 * including the overflow threshold above the largest finite number. */
static int compare_mid(const char *s, size_t end, int order, bool sticky,
                       uint64_t b)
{
    int field = (int)(b >> 52);
    uint64_t m = b & ((UINT64_C(1) << 52) - 1);
    if (field) m |= UINT64_C(1) << 52;
    m = 2 * m + 1;
    int k = (field ? field : 1) - 1076;
    int decimal_shift = k < 0 ? k : 0;
    struct decimal d;
    d.used = 0;
    for (int shift = 48; shift >= 0; shift -= 16)
        mul_add(&d, 65536, (uint16_t)(m >> shift));
    while (k <= -8) { mul_add(&d, 390625, 0); k += 8; }
    while (k < 0) { mul_add(&d, 5, 0); ++k; }
    while (k >= 16) { mul_add(&d, 65536, 0); k -= 16; }
    if (k) mul_add(&d, UINT32_C(1) << k, 0);
    uint32_t divisor = 1;
    int mid_order = (d.used - 1) * 4 + decimal_shift;
    while (d.limb[d.used-1] / divisor >= 10) { divisor *= 10; ++mid_order; }
    if (order != mid_order) return order < mid_order ? -1 : 1;
    int limb = d.used - 1;
    for (size_t i = 0; i < end || limb >= 0; ++i) {
        if (i < end && s[i] == '.') continue;
        unsigned actual = i < end ? (unsigned)(s[i] - '0') : 0;
        unsigned expected = limb < 0 ? 0 : d.limb[limb] / divisor % 10;
        if (actual != expected) return actual < expected ? -1 : 1;
        if (divisor == 1) { --limb; divisor = 1000; }
        else divisor /= 10;
    }
    return sticky ? 1 : 0;
}

static int clamp_size(size_t x) { return x > 2000 ? 2000 : (int)x; }

/* The exponent magnitude is prefix*10+last. Subtract the decimal-point
 * displacement before clamping, even when the full exponent exceeds SIZE_MAX. */
static int decimal_order(size_t offset, bool left, size_t prefix, int last,
                         bool negative)
{
    int value;
    if (left == negative) value = clamp_size(offset) + 10*clamp_size(prefix) + last;
    else {
        size_t tens = offset / 10;
        int diff = prefix >= tens ? clamp_size(prefix - tens) : -clamp_size(tens - prefix);
        value = 10*diff + last - (int)(offset % 10);
    }
    return negative ? -value : value;
}

bool elya_parse_f64(const char *s, size_t n, double *out)
{
    if (!s || !out || !n) return false;
    size_t i = 0;
    uint64_t sign = s[0] == '-' ? SIGN_BIT : 0;
    if (sign || s[0] == '+') ++i;
    uint64_t bits = 0;
    if (i == n) return false;
    if (!digit(s[i])) {
        if (word(s+i, n-i, "inf") || word(s+i, n-i, "infinity")) bits = INF_BITS;
        else if (word(s+i, n-i, "nan")) bits = INF_BITS | (UINT64_C(1) << 51);
        else return false;
    } else {
        size_t first = n, point = n, prefix_end = n;
        unsigned kept = 0;
        bool sticky = false, tail = false;
        uint64_t w = 0;
        while (i < n) {
            char c = s[i];
            if (c == '.' && point == n) {
                point = i++;
                if (i == n || !digit(s[i])) return false;
                continue;
            }
            if (!digit(c)) break;
            if (c != '0' && first == n) first = i;
            if (first != n) {
                if (kept < 19) w = w*10 + (unsigned)(c-'0');
                else if (c != '0') tail = true;
                if (kept < 800) ++kept;
                else {
                    if (prefix_end == n) prefix_end = i;
                    if (c != '0') sticky = true;
                }
            }
            ++i;
        }
        size_t end = i;
        if (point == n) point = end;
        if (prefix_end == n) prefix_end = end;
        bool neg_exp = false;
        size_t prefix = 0;
        int last = 0;
        if (i < n) {
            if (s[i] != 'e' && s[i] != 'E') return false;
            ++i;
            if (i < n && (s[i] == '+' || s[i] == '-')) neg_exp = s[i++] == '-';
            if (i == n) return false;
            for (; i < n; ++i) {
                if (!digit(s[i])) return false;
                if (prefix > (SIZE_MAX - (unsigned)last)/10) prefix = SIZE_MAX;
                else prefix = prefix*10 + (unsigned)last;
                last = s[i]-'0';
            }
        }
        if (w) {
            bool left = first > point;
            size_t offset = left ? first-point : point-first-1;
            int order = decimal_order(offset, left, prefix, last, neg_exp);
            if (order > 308) bits = INF_BITS;
            else if (order >= -324) {
                int q = order - (int)(kept < 19 ? kept : 19) + 1;
                uint64_t lo = product_bound(w, q, false);
                uint64_t hi = product_bound(w + tail, q, true);
                while (lo < hi) {
                    uint64_t b = lo + (hi-lo)/2;
                    int cmp = compare_mid(s+first, prefix_end-first, order, sticky, b);
                    if (cmp > 0 || (cmp == 0 && (b & 1))) lo = b+1;
                    else hi = b;
                }
                bits = lo;
            }
        }
    }
    union { uint64_t u; double d; } result;
    result.u = sign | bits;
    *out = result.d;
    return true;
}
