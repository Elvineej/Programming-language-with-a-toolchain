static wide product(uint64_t a, uint64_t b)
{
    uint64_t ah = a >> 32, bh = b >> 32;
    uint64_t al = (uint32_t)a, bl = (uint32_t)b;
    uint64_t low = al * bl;
    uint64_t cross = ah * bl + (low >> 32);
    uint64_t mid = al * bh + (uint32_t)cross;
    wide p = { ah * bh + (cross >> 32) + (mid >> 32),
               (mid << 32) | (uint32_t)low };
    return p;
}

/* Exact division via ceil(2^67 / 10). Avoid a runtime division on ILP32. */
static uint64_t tenth(uint64_t n)
{
    return product(n, UINT64_C(0xcccccccccccccccd)).hi >> 3;
}

static int floor_fixed(int n)
{
    return n >= 0 ? n / 65536 : -1 - ((-1 - n) / 65536);
}

/* Exact comparison for the rare case in which the cached power's error
 * straddles an integer. Cancel common factors of 2 and 5 first.
 * Each side fits in 1200 bits over the binary64 exponent range. */
typedef struct { uint32_t limb[38]; unsigned used; } big;

static void init_big(big *v, uint64_t n)
{
    v->limb[0] = (uint32_t)n;
    v->limb[1] = (uint32_t)(n >> 32);
    v->used = v->limb[1] ? 2 : 1;
}

static void multiply_small(big *v, uint32_t factor)
{
    uint64_t carry = 0;
    for (unsigned i = 0; i < v->used; ++i) {
        uint64_t t = (uint64_t)v->limb[i] * factor + carry;
        v->limb[i] = (uint32_t)t;
        carry = t >> 32;
    }
    if (carry) v->limb[v->used++] = (uint32_t)carry;
}

static bool reaches(uint64_t m, int twos, int fives, uint64_t integer)
{
    big a, b;
    init_big(&a, m);
    init_big(&b, integer);
    while (twos > 0) { multiply_small(&a, 2); --twos; }
    while (twos < 0) { multiply_small(&b, 2); ++twos; }
    while (fives > 0) { multiply_small(&a, 5); --fives; }
    while (fives < 0) { multiply_small(&b, 5); ++fives; }
    if (a.used != b.used) return a.used > b.used;
    for (unsigned i = a.used; i-- > 0;) {
        if (a.limb[i] != b.limb[i]) return a.limb[i] > b.limb[i];
    }
    return true;
}

static bool integral(uint64_t m, int twos, int fives)
{
    if (twos < 0 && (twos <= -64 || (m & ((UINT64_C(1) << -twos) - 1))))
        return false;
    while (fives < 0) {
        uint64_t q = tenth(m) * 2;
        if (m - q * 5 >= 5) ++q;
        if (q * 5 != m) return false;
        m = q;
        ++fives;
    }
    return true;
}

/* Floor of m * 2^e * 10^k. The unsigned 192-bit product uses three
 * limbs. Replacing the cached multiplier by its exact value adds < m
 * to that product, so only a carry across the shift can affect the floor. */
static uint64_t scaled(uint64_t m, int e, int k, unsigned shift, wide power)
{
    wide a = product(m, power.lo), b = product(m, power.hi);
    uint64_t mid = a.hi + b.lo;
    uint64_t hi = b.hi + (mid < a.hi);
    uint64_t mask = (UINT64_C(1) << shift) - 1;
    uint64_t n = (hi << (64 - shift)) | (mid >> shift);
    if ((mid & mask) == mask && a.lo > UINT64_MAX - m &&
        (integral(m, e + k, k) || reaches(m, e + k, k, n + 1)))
        ++n;
    return n;
}

size_t elya_fmt_f64(double x, char *out)
{
    union { double d; uint64_t u; } bits = { x };
    typedef char binary64_required[sizeof(double) == sizeof(uint64_t) ? 1 : -1];
    (void)sizeof(binary64_required);
    uint64_t frac = bits.u & UINT64_C(0xfffffffffffff);
    unsigned exp = (unsigned)(bits.u >> 52) & 2047;
    size_t pos = 0;
    if (exp == 2047 && frac) {
        out[0] = 'N'; out[1] = 'a'; out[2] = 'N'; return 3;
    }
    if (bits.u >> 63) out[pos++] = '-';
    if (exp == 2047) {
        out[pos++] = 'i'; out[pos++] = 'n'; out[pos++] = 'f'; return pos;
    }
    if (!exp && !frac) { out[pos++] = '0'; return pos; }

    uint64_t sig = exp ? frac + (UINT64_C(1) << 52) : frac;
    int e = (exp ? (int)exp : 1) - 1077;
    uint64_t center = sig * 4;
    uint64_t left = center - (frac == 0 && exp > 1 ? 1 : 2);
    uint64_t right = center + 2;
    /* The grid scale lies in [1,100). These fixed-point floors agree
     * with the exact logarithms throughout their respective ranges. */
    int lognum = e * 315653;
    int d = lognum >= 0 ? lognum / 1048576 : -1 - ((-1 - lognum) / 1048576);
    if (d % 2) --d;
    int k = -d;
    /* floor(k*log2(10)) uses a finer approximation for this range. */
    int logpower = floor_fixed(k * 217706);
    unsigned shift = (unsigned)(63 - logpower - e);
    wide power = powers[(k + 290) / 2];
    bool even = (sig & 1) == 0;
    uint64_t low = scaled(left, e, k, shift, power);
    uint64_t high = scaled(right, e, k, shift, power);
    if (!even || !integral(left, e + k, k)) ++low;
    if (!even && integral(right, e + k, k)) --high;

    /* [low,high] is the closed interval of legal grid integers. Coarsen
     * until it contains no multiple of ten. Keep the first discarded
     * digit to round the exact center, including Rust's upward ties. */
    uint64_t twice = scaled(2 * center, e, k, shift, power);
    uint64_t n = twice >> 1;
    bool up = (twice & 1) != 0;
    for (;;) {
        uint64_t next_low = tenth(low + 9), next_high = tenth(high);
        if (next_low > next_high) break;
        uint64_t q = tenth(n);
        up = n - 10 * q >= 5;
        n = q; low = next_low; high = next_high; ++d;
    }
    n += up;
    if (n < low) n = low;
    if (n > high) n = high;

    char reversed[20];
    int count = 0;
    do {
        uint64_t q = tenth(n);
        reversed[count++] = (char)('0' + (n - q * 10));
        n = q;
    } while (n);
    int point = count + d;
    if (point <= 0) {
        out[pos++] = '0'; out[pos++] = '.';
        for (int i = point; i < 0; ++i) out[pos++] = '0';
    }
    for (int i = 0; i < count; ++i) {
        if (i && i == point) out[pos++] = '.';
        out[pos++] = reversed[count - i - 1];
    }
    for (int i = 0; i < d; ++i) out[pos++] = '0';
    return pos;
}
